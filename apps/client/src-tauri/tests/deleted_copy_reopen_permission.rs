use serde_json::{Value, json};

#[test]
fn deleted_copy_reopen_requires_main_window_permission() {
    let manifest = include_str!("../build.rs");
    let handler = include_str!("../src/lib.rs");
    let capability: Value =
        serde_json::from_str(include_str!("../capabilities/main.json")).unwrap();
    assert_eq!(capability["windows"], json!(["main"]));
    {
        let command = "workspace_reopen_deleted_draft_copy";
        assert!(manifest.contains(&format!("\"{command}\"")), "{command}");
        assert!(
            handler.contains(&format!("remote_deleted_copy_native::{command}")),
            "{command}"
        );
        let permission_id = format!("allow-{}", command.replace('_', "-"));
        assert!(
            capability["permissions"]
                .as_array()
                .unwrap()
                .iter()
                .any(|entry| entry.as_str() == Some(permission_id.as_str())),
            "{command}"
        );
        let permission = std::fs::read_to_string(
            std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
                .join(format!("permissions/autogenerated/{command}.toml")),
        )
        .unwrap();
        assert!(permission.contains(&format!("identifier = \"{permission_id}\"")));
        assert!(permission.contains(&format!("commands.allow = [\"{command}\"]")));
    }
}
