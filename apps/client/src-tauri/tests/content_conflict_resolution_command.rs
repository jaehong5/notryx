use notryx_protocol::{WorkspaceConflictResolutionRequest, WorkspaceConflictResolutionResponse};
use serde_json::{Value, json};

fn binding() -> Value {
    json!({
        "server_origin":"https://workspace.example",
        "workspace_id":"019a1000-0000-7000-8000-000000000001",
        "workspace_epoch":"019a1000-0000-7000-8000-000000000002",
        "device_id":"019a1000-0000-7000-8000-000000000003",
        "device_stream_id":"019a1000-0000-7000-8000-000000000004"
    })
}

fn request() -> Value {
    json!({"renderer_session_id":"owner", "binding":binding(),
        "document_id":"019a1000-0000-7000-8000-000000000005",
        "operation_id":"019a1000-0000-7000-8000-000000000006"})
}

fn response(state: Value) -> Value {
    json!({"binding":binding(), "document_id":"019a1000-0000-7000-8000-000000000005",
        "operation_id":"019a1000-0000-7000-8000-000000000006", "state":state})
}

#[test]
fn status_request_and_response_reject_unknown_fields_and_invalid_enum_values() {
    assert!(serde_json::from_value::<WorkspaceConflictResolutionRequest>(request()).is_ok());
    let mut extra = request();
    extra["unexpected"] = json!(true);
    assert!(serde_json::from_value::<WorkspaceConflictResolutionRequest>(extra).is_err());
    let mut extra_binding = request();
    extra_binding["binding"]["unexpected"] = json!(true);
    assert!(serde_json::from_value::<WorkspaceConflictResolutionRequest>(extra_binding).is_err());
    let valid = response(json!({"status":"pending", "version":"0", "generation":"1",
        "choice":"choose_remote", "needs_review":false, "frozen":false}));
    assert!(serde_json::from_value::<WorkspaceConflictResolutionResponse>(valid.clone()).is_ok());
    let mut extra = valid.clone();
    extra["unexpected"] = json!(true);
    assert!(serde_json::from_value::<WorkspaceConflictResolutionResponse>(extra).is_err());
    let mut extra = valid.clone();
    extra["state"]["remote_bytes"] = json!("secret");
    assert!(serde_json::from_value::<WorkspaceConflictResolutionResponse>(extra).is_err());
    let mut bad_choice = valid.clone();
    bad_choice["state"]["choice"] = json!("unknown_choice");
    assert!(serde_json::from_value::<WorkspaceConflictResolutionResponse>(bad_choice).is_err());
    let mut bad_status = valid;
    bad_status["state"]["status"] = json!("unknown_status");
    assert!(serde_json::from_value::<WorkspaceConflictResolutionResponse>(bad_status).is_err());
}

#[test]
fn status_response_decimal_fields_enforce_unsigned_string_range() {
    for field in ["version", "generation"] {
        for value in [json!("0"), json!("1"), json!("18446744073709551615")] {
            let mut item = response(json!({"status":"pending", "version":"0", "generation":"1",
                "choice":"choose_remote", "needs_review":false, "frozen":false}));
            item["state"][field] = value;
            assert!(
                serde_json::from_value::<WorkspaceConflictResolutionResponse>(item).is_ok(),
                "field={field}"
            );
        }
        for value in [
            json!(""),
            json!("-1"),
            json!("+1"),
            json!("18446744073709551616"),
            json!(1),
            json!(null),
            json!(false),
        ] {
            let mut item = response(json!({"status":"pending", "version":"0", "generation":"1",
                "choice":"choose_remote", "needs_review":false, "frozen":false}));
            item["state"][field] = value;
            assert!(
                serde_json::from_value::<WorkspaceConflictResolutionResponse>(item).is_err(),
                "field={field}"
            );
        }
    }
    let completed = response(
        json!({"status":"completed", "generation":"18446744073709551616", "frozen":false}),
    );
    assert!(serde_json::from_value::<WorkspaceConflictResolutionResponse>(completed).is_err());
}

#[test]
fn command_is_registered_with_explicit_main_window_permission() {
    let command = "workspace_content_conflict_resolution_status";
    let manifest = include_str!("../build.rs");
    let handler = include_str!("../src/lib.rs");
    let capability: Value =
        serde_json::from_str(include_str!("../capabilities/main.json")).unwrap();
    assert!(manifest.contains(&format!("\"{command}\"")));
    assert!(handler.contains(&format!("conflict_snapshot_native::{command}")));
    assert_eq!(capability["windows"], json!(["main"]));
    assert!(
        capability["permissions"]
            .as_array()
            .unwrap()
            .iter()
            .any(|entry| entry == "allow-workspace-content-conflict-resolution-status")
    );
    let permission_path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("permissions/autogenerated/workspace_content_conflict_resolution_status.toml");
    let permission = std::fs::read_to_string(permission_path).unwrap();
    assert!(
        permission.contains("identifier = \"allow-workspace-content-conflict-resolution-status\"")
    );
    assert!(
        permission.contains("commands.allow = [\"workspace_content_conflict_resolution_status\"]")
    );
}
