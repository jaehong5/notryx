use notryx_protocol::WorkspaceContentConflictCopyRetryRequest;
use serde_json::{Value, json};

fn request() -> Value {
    json!({"progress":{"renderer_session_id":"owner","binding":{"server_origin":"https://workspace.example","workspace_id":"019a1000-0000-7000-8000-000000000001","workspace_epoch":"019a1000-0000-7000-8000-000000000002","device_id":"019a1000-0000-7000-8000-000000000003","device_stream_id":"019a1000-0000-7000-8000-000000000004"},"document_id":"document","edit_session_id":"session","operation_id":"conflict","expected_intent_version":"1"},"expected_create_operation_id":"old-create","parent_id":"parent","name":"retry.md"})
}

#[test]
fn retry_copy_request_keeps_failed_create_and_confirmed_destination() {
    let valid = request();
    assert!(
        serde_json::from_value::<WorkspaceContentConflictCopyRetryRequest>(valid.clone()).is_ok()
    );
    for field in ["expected_create_operation_id", "parent_id", "name"] {
        let mut missing = valid.clone();
        missing.as_object_mut().unwrap().remove(field);
        assert!(
            serde_json::from_value::<WorkspaceContentConflictCopyRetryRequest>(missing).is_err()
        );
    }
    let mut version = valid.clone();
    version["progress"]["expected_intent_version"] = json!("-1");
    assert!(serde_json::from_value::<WorkspaceContentConflictCopyRetryRequest>(version).is_err());
    let mut extra = valid;
    extra["extra"] = json!(true);
    assert!(serde_json::from_value::<WorkspaceContentConflictCopyRetryRequest>(extra).is_err());
}

#[test]
fn retry_copy_command_is_limited_to_main_window() {
    let command = "workspace_retry_content_conflict_copy";
    let permission = "allow-workspace-retry-content-conflict-copy";
    let manifest = include_str!("../build.rs");
    let handler = include_str!("../src/lib.rs");
    let capability: Value =
        serde_json::from_str(include_str!("../capabilities/main.json")).unwrap();
    assert!(manifest.contains(&format!("\"{command}\"")));
    assert!(handler.contains(&format!("conflict_snapshot_native::{command}")));
    assert_eq!(capability["windows"], json!(["main"]));
    assert!(
        capability["permissions"]
            .as_array()
            .unwrap()
            .iter()
            .any(|entry| entry == permission)
    );
    let generated = std::fs::read_to_string(
        std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("permissions/autogenerated")
            .join(format!("{command}.toml")),
    )
    .unwrap();
    assert!(generated.contains(&format!("identifier = \"{permission}\"")));
    assert!(generated.contains(&format!("commands.allow = [\"{command}\"]")));
}
