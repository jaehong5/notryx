use serde_json::{Value, json};
use std::path::Path;

#[test]
fn frozen_content_inspection_is_registered_for_local_main_only() {
    let command = "workspace_inspect_frozen_content";
    let allow = "allow-workspace-inspect-frozen-content";
    let deny = "deny-workspace-inspect-frozen-content";
    let manifest = include_str!("../build.rs");
    let handler = include_str!("../src/lib.rs");
    let source = include_str!("../src/frozen_content_native.rs");
    let capability: Value =
        serde_json::from_str(include_str!("../capabilities/main.json")).unwrap();
    let config: Value = serde_json::from_str(include_str!("../tauri.conf.json")).unwrap();

    assert!(manifest.contains(&format!("\"{command}\"")));
    assert!(handler.contains(&format!("frozen_content_native::{command}")));
    assert_eq!(capability["windows"], json!(["main"]));
    assert!(capability.get("remote").is_none());
    assert_eq!(
        config["app"]["security"]["capabilities"],
        json!(["main", "mermaid"])
    );
    assert!(
        capability["permissions"]
            .as_array()
            .unwrap()
            .iter()
            .any(|value| value == allow)
    );

    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    for entry in std::fs::read_dir(root.join("capabilities")).unwrap() {
        let path = entry.unwrap().path();
        if path.file_name().and_then(|name| name.to_str()) == Some("main.json")
            || path.extension().and_then(|ext| ext.to_str()) != Some("json")
        {
            continue;
        }
        let other: Value = serde_json::from_slice(&std::fs::read(&path).unwrap()).unwrap();
        assert!(
            !other["permissions"]
                .as_array()
                .unwrap()
                .iter()
                .any(|value| {
                    value.as_str() == Some(allow)
                        || value.get("identifier").and_then(Value::as_str) == Some(allow)
                }),
            "another capability grants frozen content inspection"
        );
    }

    let permission = std::fs::read_to_string(
        root.join("permissions/autogenerated")
            .join(format!("{command}.toml")),
    )
    .unwrap();
    assert!(permission.contains(&format!("identifier = \"{allow}\"")));
    assert!(permission.contains(&format!("commands.allow = [\"{command}\"]")));
    assert!(permission.contains(&format!("identifier = \"{deny}\"")));
    assert!(permission.contains(&format!("commands.deny = [\"{command}\"]")));

    let start = source.find(&format!("async fn {command}(")).unwrap();
    let remainder = &source[start..];
    let end = remainder.find("\n}").unwrap() + 2;
    let command_body = &remainder[..end];
    let before_await = command_body.find(".await").unwrap();
    let first_check = command_body.find("check_caller(&webview)").unwrap();
    assert!(first_check < before_await);
    assert!(command_body[before_await..].contains("check_caller(&webview)"));
}
