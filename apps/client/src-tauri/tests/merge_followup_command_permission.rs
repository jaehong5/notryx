use serde_json::{Value, json};

#[test]
fn merge_followup_commands_are_registered_with_main_window_permission() {
    let manifest = include_str!("../build.rs");
    let handler = include_str!("../src/lib.rs");
    let capability: Value =
        serde_json::from_str(include_str!("../capabilities/main.json")).unwrap();
    assert_eq!(capability["windows"], json!(["main"]));
    let permissions = capability["permissions"].as_array().unwrap();
    for (command, allow) in [
        (
            "workspace_content_conflict_merge_followup_status",
            "allow-workspace-content-conflict-merge-followup-status",
        ),
        (
            "workspace_request_content_conflict_merge_followup_abandon",
            "allow-workspace-request-content-conflict-merge-followup-abandon",
        ),
    ] {
        assert!(
            manifest.contains(&format!("\"{command}\"")),
            "manifest: {command}"
        );
        assert!(
            handler.contains(&format!("conflict_snapshot_native::{command}")),
            "handler: {command}"
        );
        assert!(
            permissions.iter().any(|entry| entry == allow),
            "capability: {command}"
        );
        let permission = std::fs::read_to_string(
            std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
                .join("permissions/autogenerated")
                .join(format!("{command}.toml")),
        )
        .unwrap();
        assert!(
            permission.contains(&format!("identifier = \"{allow}\"")),
            "identifier: {command}"
        );
        assert!(
            permission.contains(&format!("commands.allow = [\"{command}\"]")),
            "command: {command}"
        );
    }
}
