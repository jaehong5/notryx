use notryx_protocol::{
    WorkspaceContentConflictCopyProgressRequest, WorkspaceContentConflictCopyProgressResponse,
    WorkspaceContentConflictCopyStatusResponse,
};
use serde_json::{Value, json};

fn binding() -> Value {
    json!({"server_origin":"https://workspace.example","workspace_id":"019a1000-0000-7000-8000-000000000001","workspace_epoch":"019a1000-0000-7000-8000-000000000002","device_id":"019a1000-0000-7000-8000-000000000003","device_stream_id":"019a1000-0000-7000-8000-000000000004"})
}

#[test]
fn copy_progress_contract_requires_explicit_optional_approval_and_valid_version() {
    let request = json!({"progress":{"renderer_session_id":"owner","binding":binding(),"document_id":"document","edit_session_id":"session","operation_id":"conflict","expected_intent_version":"1"},"approved_followup_operation_id":null});
    assert!(
        serde_json::from_value::<WorkspaceContentConflictCopyProgressRequest>(request.clone())
            .is_ok()
    );
    let mut invalid = request.clone();
    invalid["progress"]["expected_intent_version"] = json!("-1");
    assert!(
        serde_json::from_value::<WorkspaceContentConflictCopyProgressRequest>(invalid).is_err()
    );
    let mut invalid = request;
    invalid["extra"] = json!(true);
    assert!(
        serde_json::from_value::<WorkspaceContentConflictCopyProgressRequest>(invalid).is_err()
    );
    for response in [
        json!({"status":"approval_required","followup_operation_id":"followup"}),
        json!({"status":"pending","requested_operation_id":null}),
        json!({"status":"pending","requested_operation_id":"followup"}),
        json!({"status":"saved"}),
        json!({"status":"needs_review"}),
    ] {
        assert!(
            serde_json::from_value::<WorkspaceContentConflictCopyProgressResponse>(response)
                .is_ok()
        );
    }
    assert!(
        serde_json::from_value::<WorkspaceContentConflictCopyProgressResponse>(
            json!({"status":"saved","extra":true})
        )
        .is_err()
    );
}

#[test]
fn copy_status_contract_distinguishes_target_and_save_progress() {
    let response = json!({"binding":binding(),"document_id":"document","operation_id":"conflict","copy":{"version":"1","parent_id":"parent","name":"copy.md","node_id":"copy","create_operation_id":"create","followup_operation_id":null,"create_status":"created","create_failure":null,"content_status":"saved"}});
    assert!(
        serde_json::from_value::<WorkspaceContentConflictCopyStatusResponse>(response.clone())
            .is_ok()
    );
    let mut wrong = response.clone();
    wrong["copy"]["version"] = json!("-1");
    assert!(serde_json::from_value::<WorkspaceContentConflictCopyStatusResponse>(wrong).is_err());
    let mut wrong = response;
    wrong["copy"]["content_status"] = json!("unknown");
    assert!(serde_json::from_value::<WorkspaceContentConflictCopyStatusResponse>(wrong).is_err());
}

#[test]
fn copy_progress_and_status_are_registered_only_to_main_window() {
    let manifest = include_str!("../build.rs");
    let handler = include_str!("../src/lib.rs");
    let capability: Value =
        serde_json::from_str(include_str!("../capabilities/main.json")).unwrap();
    assert_eq!(capability["windows"], json!(["main"]));
    for (command, permission) in [
        (
            "workspace_progress_content_conflict_copy",
            "allow-workspace-progress-content-conflict-copy",
        ),
        (
            "workspace_content_conflict_copy_status",
            "allow-workspace-content-conflict-copy-status",
        ),
    ] {
        assert!(manifest.contains(&format!("\"{command}\"")));
        assert!(handler.contains(&format!("conflict_snapshot_native::{command}")));
        assert!(
            capability["permissions"]
                .as_array()
                .unwrap()
                .iter()
                .any(|entry| entry == permission)
        );
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("permissions/autogenerated")
            .join(format!("{command}.toml"));
        let generated = std::fs::read_to_string(path).unwrap();
        assert!(generated.contains(&format!("identifier = \"{permission}\"")));
        assert!(generated.contains(&format!("commands.allow = [\"{command}\"]")));
    }
}
