use notryx_protocol::{WorkspaceContentConflictCopyRequest, WorkspaceContentConflictCopyResponse};
use serde_json::{Value, json};

fn valid_request() -> Value {
    let hash = format!("sha256:{}", "a".repeat(64));
    json!({"selection": {"renderer_session_id":"owner",
        "binding":{"server_origin":"https://workspace.example","workspace_id":"019a1000-0000-7000-8000-000000000001","workspace_epoch":"019a1000-0000-7000-8000-000000000002","device_id":"019a1000-0000-7000-8000-000000000003","device_stream_id":"019a1000-0000-7000-8000-000000000004"},
        "document_id":"019a1000-0000-7000-8000-000000000005","edit_session_id":"session","operation_id":"019a1000-0000-7000-8000-000000000006",
        "generation":"1","expected_intent_version":null,"base_revision":"base","conflict_revision":"failed","remote_revision":"remote",
        "base_hash":hash,"local_hash":hash,"remote_hash":hash},"parent_id":"019a1000-0000-7000-8000-000000000001","name":"copy.md"})
}

#[test]
fn copy_confirm_request_validates_nested_snapshot_and_rejects_extra_fields() {
    let valid = valid_request();
    assert!(serde_json::from_value::<WorkspaceContentConflictCopyRequest>(valid.clone()).is_ok());
    for (scope, field, value) in [
        ("selection", "generation", json!("-1")),
        (
            "selection",
            "expected_intent_version",
            json!("18446744073709551616"),
        ),
        ("selection", "local_hash", json!("sha256:bad")),
        ("selection", "extra", json!(true)),
    ] {
        let mut request = valid.clone();
        request[scope][field] = value;
        assert!(serde_json::from_value::<WorkspaceContentConflictCopyRequest>(request).is_err());
    }
    let mut extra = valid.clone();
    extra["extra"] = json!(true);
    assert!(serde_json::from_value::<WorkspaceContentConflictCopyRequest>(extra).is_err());
    for field in ["parent_id", "name"] {
        let mut missing = valid.clone();
        missing.as_object_mut().unwrap().remove(field);
        assert!(serde_json::from_value::<WorkspaceContentConflictCopyRequest>(missing).is_err());
    }
}

#[test]
fn copy_confirm_response_requires_pending_and_decimal_version() {
    let valid = json!({"status":"pending","version":"0","node_id":"new-node","create_operation_id":"new-operation"});
    assert!(serde_json::from_value::<WorkspaceContentConflictCopyResponse>(valid.clone()).is_ok());
    for invalid in [
        json!("-1"),
        json!("18446744073709551616"),
        json!(1),
        json!(null),
    ] {
        let mut response = valid.clone();
        response["version"] = invalid;
        assert!(serde_json::from_value::<WorkspaceContentConflictCopyResponse>(response).is_err());
    }
    let mut extra = valid;
    extra["raw_bytes"] = json!("forbidden");
    assert!(serde_json::from_value::<WorkspaceContentConflictCopyResponse>(extra).is_err());
}

#[test]
fn copy_confirm_is_registered_with_main_window_permission() {
    let command = "workspace_confirm_content_conflict_copy";
    let manifest = include_str!("../build.rs");
    let handler = include_str!("../src/lib.rs");
    let capability: Value =
        serde_json::from_str(include_str!("../capabilities/main.json")).unwrap();
    assert!(manifest.contains(&format!("\"{command}\"")));
    assert!(handler.contains(&format!("conflict_snapshot_native::{command}")));
    assert_eq!(capability["windows"], json!(["main"]));
    assert!(
        capability["permissions"]
            .as_array()
            .unwrap()
            .iter()
            .any(|entry| entry == "allow-workspace-confirm-content-conflict-copy")
    );
    let permission = std::fs::read_to_string(
        std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("permissions/autogenerated/workspace_confirm_content_conflict_copy.toml"),
    )
    .unwrap();
    assert!(permission.contains("identifier = \"allow-workspace-confirm-content-conflict-copy\""));
    assert!(permission.contains("commands.allow = [\"workspace_confirm_content_conflict_copy\"]"));
}
