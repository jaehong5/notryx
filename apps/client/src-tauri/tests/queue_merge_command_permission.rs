use serde_json::{Value, json};

#[test]
fn merge_queue_is_registered_with_main_window_permission() {
    let command = "workspace_queue_content_conflict_merge";
    let manifest = include_str!("../build.rs");
    let handler = include_str!("../src/lib.rs");
    let capability: Value =
        serde_json::from_str(include_str!("../capabilities/main.json")).unwrap();
    assert!(manifest.contains(&format!("\"{command}\"")));
    assert!(handler.contains(&format!("conflict_snapshot_native::{command}")));
    assert_eq!(capability["windows"], json!(["main"]));
    assert!(
        capability["permissions"]
            .as_array()
            .unwrap()
            .iter()
            .any(|entry| entry == "allow-workspace-queue-content-conflict-merge")
    );
    let permission = std::fs::read_to_string(
        std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("permissions/autogenerated/workspace_queue_content_conflict_merge.toml"),
    )
    .unwrap();
    assert!(permission.contains("identifier = \"allow-workspace-queue-content-conflict-merge\""));
    assert!(permission.contains("commands.allow = [\"workspace_queue_content_conflict_merge\"]"));
}
